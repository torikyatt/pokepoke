const shuffle = <T,>(xs: T[]): T[] => {
  const a = [...xs];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
};

/** 例をランダムに選ぶ（ふだんの言葉の例 talk 個と、カード名・決まった言い方の例 basic 個を混ぜる） */
export function pickExamples(lang: "ja" | "en", talk = 9, basic = 3): string[] {
  const src = lang === "en" ? EXAMPLES_EN : EXAMPLES_JA;
  return shuffle([...shuffle(src.talk).slice(0, talk), ...shuffle(src.basic).slice(0, basic)]);
}
